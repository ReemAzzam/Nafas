export function isWithinSyria({ lat, lng }: Coordinates): boolean {
  if (
    !Number.isFinite(lat)
    || !Number.isFinite(lng)
    || lat < SYRIA_MAP_LIMITS.south
    || lat > SYRIA_MAP_LIMITS.north
    || lng < SYRIA_MAP_LIMITS.west
    || lng > SYRIA_MAP_LIMITS.east
  ) {
    return false;
  }

  let inside = false;
  for (let i = 0, j = syriaBoundary.length - 1; i < syriaBoundary.length; j = i++) {
    const [latI, lngI] = syriaBoundary[i];
    const [latJ, lngJ] = syriaBoundary[j];
    const cross = (lng - lngI) * (latJ - latI) - (lat - latI) * (lngJ - lngI);
    if (
      Math.abs(cross) < 1e-8
      && lng >= Math.min(lngI, lngJ) - 1e-8
      && lng <= Math.max(lngI, lngJ) + 1e-8
      && lat >= Math.min(latI, latJ) - 1e-8
      && lat <= Math.max(latI, latJ) + 1e-8
    ) {
      return true;
    }

    if (
      (latI > lat) !== (latJ > lat)
      && lng < ((lngJ - lngI) * (lat - latI)) / (latJ - latI) + lngI
    ) {
      inside = !inside;
    }
  }

  return inside;
}

export function parseSyriaCoordinates(
  values: CoordinateValues,
): Coordinates | null {
  if (!values.lat.trim() || !values.lng.trim()) return null;
  const lat = Number(values.lat);
  const lng = Number(values.lng);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;
  const coordinates = { lat, lng };
  return isWithinSyria(coordinates) ? coordinates : null;
}

export function getSyriaCoordinatesError(
  values: CoordinateValues,
): string | null {
  if (!values.lat.trim() || !values.lng.trim()) return null;
  const lat = Number(values.lat);
  const lng = Number(values.lng);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) {
    return "أدخل إحداثيات صحيحة للموقع.";
  }
  if (!isWithinSyria({ lat, lng })) {
    return "يجب أن يكون موقع المستشار داخل حدود سوريا.";
  }
  return null;
}
